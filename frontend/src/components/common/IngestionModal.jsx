    modality: 'pptx',
    badge: 'PPTX Slides',
    desc: 'Hardware MMU & TLB Effective Access Time (EAT), Belady Anomaly vs. LRU, and Denning Working Set Thrashing model.',
    text: `Logical addresses generated by the CPU are divided into a Page Number (p) and Page Offset (d). The Translation Lookaside Buffer (TLB) is an associative hardware cache storing recent page-to-frame mappings. Effective Access Time is governed by hit ratio alpha: EAT = alpha * (t_TLB + t_mem) + (1 - alpha) * (t_TLB + 2 * t_mem).\n\nWhen a page fault occurs and no free frames exist, the OS evicts a victim page. FIFO replacement suffers from Belady Anomaly (allocating more physical frames can paradoxically increase page faults). Least Recently Used (LRU) is a stack algorithm immune to Belady Anomaly.\n\nThrashing occurs when a process spends more time paging than executing instructions because total Working Set demand exceeds physical frames.`
